const { text, joinHtml } = require('../lib/html');

const OPERATOR = '[РЕКВИЗИТЫ ПРЕДСТАВИТЕЛЬСТВА]';

function renderBanner() {
  return `<div class="template-banner" role="note">
      <b>Шаблон документа.</b> Перед публикацией сайта замените все поля
      <span class="stub">[РЕКВИЗИТЫ ПРЕДСТАВИТЕЛЬСТВА]</span> и <span class="stub">[ЗАГЛУШКА]</span>
      реальными данными и согласуйте текст с юристом.
    </div>`;
}

function renderDocument({ eyebrow, title, intro, sections }) {
  const body = sections
    .map(
      ([heading, paragraphs], index) => `<section>
        <h2>${index + 1}. ${text(heading)}</h2>
        ${joinHtml(paragraphs, (paragraph) => `<p>${text(paragraph)}</p>`)}
      </section>`,
    )
    .join('');
  return `<section class="legal">
    <div class="wrap legal-wrap">
      ${renderBanner()}
      <p class="eyebrow">${text(eyebrow)}</p>
      <h1>${text(title)}</h1>
      <p class="section-lead">${text(intro)}</p>
      <div class="prose legal-body">${body}</div>
    </div>
  </section>`;
}

